// Gezichtje per spreker in het dialoogvenster
const AVATARS = [
  ['Puck', '🦜'], ['Postbode', '📮'], ['Visser', '🎣'], ['Klaas', '👴'], ['Sjoukje', '📚'], ['Duiven', '🕊️'],
  ['Ben', '🛗'], ['Mehmet', '🐈'], ['Tineke', '🚗'], ['Eline', '🛒'], ['Anja', '💶'], ['Gerrit', '👔'],
  ['Bas', '📦'], ['Wiebe', '🔔'], ['Oma', '🍪'], ['Zuur', '👓'],
];

export class Dialog {
  constructor() {
    this.el = document.getElementById('dialog');
    this.nameEl = this.el.querySelector('.dialog-name');
    this.textEl = this.el.querySelector('.dialog-text');
    this.timer = 0;
    this.index = {};
  }

  /** Volgende zin van een vaste lijst. */
  next(id) {
    const lines = NPC_LINES[id];
    const i = this.index[id] || 0;
    this.index[id] = (i + 1) % lines.length;
    return lines[i];
  }

  show(name, text, seconds = 4.5) {
    const av = AVATARS.find(([k]) => name.includes(k));
    this.nameEl.textContent = `${av ? av[1] + ' ' : ''}${name}`;
    this.full = text;
    this.shown = 0;
    this.textEl.textContent = '';
    this.el.classList.remove('hidden');
    this.el.classList.remove('pop');
    void this.el.offsetWidth;
    this.el.classList.add('pop');
    // Lang genoeg in beeld om rustig te lezen
    this.timer = Math.max(seconds, 2.5 + text.length * 0.06) + text.length / 55;
  }

  hide() {
    this.el.classList.add('hidden');
    this.timer = 0;
  }

  update(dt) {
    if (this.full && this.shown < this.full.length) {
      this.shown = Math.min(this.full.length, this.shown + dt * 55);
      this.textEl.textContent = this.full.slice(0, Math.ceil(this.shown));
    }
    if (this.timer > 0) {
      this.timer -= dt;
      if (this.timer <= 0) this.hide();
    }
  }
}
